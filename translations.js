let currentLanguage = localStorage.getItem('portfolio-language') || 'en';

function getTranslation(lang, key) {
    const keys = key.split('.');
    let translation = translations[lang];
    for (const k of keys) {
        translation = translation?.[k];
    }
    return translation;
}

function localizedText(field, lang = currentLanguage) {
    if (!field) return '';
    if (typeof field === 'string') return field;
    return field[lang] || field.en || '';
}

function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('portfolio-language', lang);

    const dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('dir', dir);
    document.documentElement.setAttribute('lang', lang);
    document.body.setAttribute('dir', dir);

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const translation = getTranslation(lang, element.getAttribute('data-i18n'));
        if (translation) {
            element.textContent = translation;
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const translation = getTranslation(lang, element.getAttribute('data-i18n-placeholder'));
        if (translation) {
            element.placeholder = translation;
        }
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(element => {
        const translation = getTranslation(lang, element.getAttribute('data-i18n-aria'));
        if (translation) {
            element.setAttribute('aria-label', translation);
        }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        }
    });

    updateHeroSubtitle(lang);

    if (typeof populateProjects === 'function') {
        populateProjects();
    }

    if (typeof updateProjectModalContent === 'function') {
        updateProjectModalContent();
    }

    if (typeof populateExperience === 'function') {
        populateExperience();
    }

    if (typeof populateSkills === 'function') {
        populateSkills();
    }

    if (typeof syncNavToggleLabel === 'function') {
        syncNavToggleLabel();
    }
}

function updateHeroSubtitle(lang) {
    const subtitle = translations[lang].hero.subtitle;
    const words = subtitle.split(' ');
    const subtitleElement = document.querySelector('.hero-subtitle');

    if (subtitleElement) {
        subtitleElement.innerHTML = words.map(word =>
            `<span class="subtitle-word">${word}</span>`
        ).join(' ');

        const wordElements = subtitleElement.querySelectorAll('.subtitle-word');
        wordElements.forEach((word, index) => {
            word.style.animation = 'none';
            setTimeout(() => {
                word.style.animation = `wordReveal 0.6s ease-out forwards`;
                word.style.animationDelay = `${0.5 + index * 0.2}s`;
            }, 10);
        });
    }
}

document.addEventListener('DOMContentLoaded', () => {
    setLanguage(currentLanguage);

    const languageSwitcher = document.getElementById('languageSwitcher');

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const lang = btn.getAttribute('data-lang');
            const isTouch = window.matchMedia('(hover: none), (pointer: coarse)').matches;

            if (languageSwitcher && isTouch && !languageSwitcher.classList.contains('is-open')) {
                e.preventDefault();
                languageSwitcher.classList.add('is-open');
                return;
            }

            setLanguage(lang);
            if (languageSwitcher) languageSwitcher.classList.remove('is-open');
        });
    });

    document.addEventListener('click', (e) => {
        if (!languageSwitcher) return;
        if (!languageSwitcher.contains(e.target)) {
            languageSwitcher.classList.remove('is-open');
        }
    });
});
